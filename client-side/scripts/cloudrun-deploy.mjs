#!/usr/bin/env node
/**
 * Deploy client-side to Google Cloud Run (build happens in Cloud Build, no local Docker needed).
 *
 *   node scripts/cloudrun-deploy.mjs --project=<gcp-project-id> [options]
 *
 * Options:
 *   --project=ID         GCP project id (required; set in package.json "deploy")
 *   --region=REGION      default us-east4; package.json "deploy" uses asia-southeast1 (Supabase prod is ap-southeast-1)
 *   --service=NAME       default cuanify
 *   --env-file=PATH      default .env
 *   --memory=1Gi         instance memory (Chromium image rendering needs >=1Gi)
 *   --max-instances=3    cost cap
 *   --nextauth-url=URL   override NEXTAUTH_URL (default: the service's run.app URL)
 *   --init               enable required GCP APIs first (run once per project)
 *   --cron               create/update the Cloud Scheduler job(s) after deploying
 *
 * What it does:
 *   1. Writes .env.production with only NEXT_PUBLIC_* vars (inlined at build time).
 *   2. Writes all vars to a temp YAML file (mode 600) for runtime env.
 *   3. `gcloud run deploy --source .` -> Cloud Build builds the Dockerfile.
 *   4. Removes both generated files.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import dotenv from "dotenv";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
process.chdir(root);

const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const [k, ...v] = a.replace(/^--/, "").split("=");
    return [k, v.length ? v.join("=") : true];
  }),
);

const sh = (cmd, cmdArgs, opts = {}) =>
  execFileSync(cmd, cmdArgs, { encoding: "utf8", ...opts });
const gcloud = (cmdArgs) => sh("gcloud", cmdArgs, { stdio: "inherit" });
const gcloudOut = (cmdArgs) => sh("gcloud", cmdArgs).trim();

// No fallback to gcloud's active project: it may point at an unrelated project.
const project = args.project;
const region = args.region || "us-east4";
const service = args.service || "cuanify";
const envFile = args["env-file"] || ".env";
const memory = args.memory || "1Gi";
const maxInstances = String(args["max-instances"] || 3);

if (!project) throw new Error("No GCP project. Pass --project=<id>.");
if (!fs.existsSync(envFile)) throw new Error(`Env file not found: ${envFile}`);

console.log(`\n▶ Deploying "${service}" to project=${project} region=${region}\n`);

if (args.init) {
  gcloud([
    "services", "enable",
    "run.googleapis.com",
    "cloudbuild.googleapis.com",
    "artifactregistry.googleapis.com",
    "cloudscheduler.googleapis.com",
    `--project=${project}`,
  ]);
}

const projectNumber = gcloudOut([
  "projects", "describe", project, "--format=value(projectNumber)",
]);

if (args.init) {
  // Newer projects no longer give the default build service account Editor,
  // so `run deploy --source` fails with PERMISSION_DENIED without these roles.
  const buildSa = `${projectNumber}-compute@developer.gserviceaccount.com`;
  for (const role of ["roles/run.builder", "roles/serviceusage.serviceUsageConsumer"]) {
    gcloud([
      "projects", "add-iam-policy-binding", project,
      `--member=serviceAccount:${buildSa}`,
      `--role=${role}`,
      "--condition=None",
      "--quiet",
    ]);
  }
  console.log("Waiting 60s for IAM propagation...");
  execFileSync("sleep", ["60"]);
}

const env = dotenv.parse(fs.readFileSync(envFile));

// Cloud Run URL is deterministic: https://SERVICE-PROJECTNUMBER.REGION.run.app
const serviceUrl = `https://${service}-${projectNumber}.${region}.run.app`;
env.NEXTAUTH_URL = args["nextauth-url"] || serviceUrl;

let buildVersion = "cloudrun";
try {
  buildVersion = sh("git", ["rev-parse", "--short", "HEAD"]).trim();
} catch {}

const q = (v) => JSON.stringify(String(v)); // valid for dotenv and YAML

const buildEnvPath = path.join(root, ".env.production");
const runtimeEnvPath = path.join(
  fs.mkdtempSync(path.join(os.tmpdir(), "cloudrun-env-")),
  "env.yaml",
);

const buildEnv = Object.entries(env)
  .filter(([k]) => k.startsWith("NEXT_PUBLIC_"))
  .concat([["NEXT_PUBLIC_BUILD_VERSION", buildVersion]]);
const runtimeEnv = Object.entries(env).filter(
  ([k]) => !["PORT", "K_SERVICE", "K_REVISION", "K_CONFIGURATION"].includes(k),
);

try {
  fs.writeFileSync(
    buildEnvPath,
    "# generated by scripts/cloudrun-deploy.mjs — deleted after deploy\n" +
      buildEnv.map(([k, v]) => `${k}=${q(v)}`).join("\n") + "\n",
  );
  fs.writeFileSync(
    runtimeEnvPath,
    runtimeEnv.map(([k, v]) => `${k}: ${q(v)}`).join("\n") + "\n",
    { mode: 0o600 },
  );

  gcloud([
    "run", "deploy", service,
    "--source", ".",
    `--project=${project}`,
    `--region=${region}`,
    "--allow-unauthenticated",
    "--port=8080",
    "--cpu=1",
    `--memory=${memory}`,
    "--min-instances=0", // scale to zero -> pay nothing when idle
    `--max-instances=${maxInstances}`,
    "--concurrency=40",
    "--timeout=300",
    "--cpu-boost", // faster cold starts, no extra cost while idle
    "--execution-environment=gen2",
    `--env-vars-file=${runtimeEnvPath}`,
    "--quiet",
  ]);
} finally {
  fs.rmSync(buildEnvPath, { force: true });
  fs.rmSync(path.dirname(runtimeEnvPath), { recursive: true, force: true });
}

if (args.cron) {
  if (!env.CRON_SECRET) throw new Error("CRON_SECRET missing in env file.");
  // Mirrors vercel.json crons (Vercel schedules are UTC).
  const jobs = [
    {
      name: `${service}-process-scheduled-shipments`,
      schedule: "0 4 * * *",
      path: "/api/cron/process-scheduled-shipments",
    },
  ];
  for (const job of jobs) {
    const common = [
      `--project=${project}`,
      `--location=${region}`,
      `--schedule=${job.schedule}`,
      "--time-zone=Etc/UTC",
      `--uri=${serviceUrl}${job.path}`,
      "--http-method=GET",
      `--update-headers=Authorization=Bearer ${env.CRON_SECRET}`,
      "--attempt-deadline=300s",
    ];
    let exists = true;
    try {
      gcloudOut(["scheduler", "jobs", "describe", job.name, `--project=${project}`, `--location=${region}`]);
    } catch {
      exists = false;
    }
    gcloud(
      exists
        ? ["scheduler", "jobs", "update", "http", job.name, ...common]
        : ["scheduler", "jobs", "create", "http", job.name,
            ...common.map((a) => a.replace("--update-headers", "--headers"))],
    );
  }
}

console.log(`\n✔ Done: ${serviceUrl}`);
console.log(
  `  Google OAuth redirect URI to whitelist: ${env.NEXTAUTH_URL}/api/auth/callback/google\n`,
);
